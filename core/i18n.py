def translate(key: str, lang: str = "zh_CN") -> str:
    """按语言返回文案；缺 key 时回退中文，再回退 key 本身。"""
    lang = lang if lang in TRANSLATIONS else "zh_CN"
    return TRANSLATIONS[lang].get(key) or TRANSLATIONS["zh_CN"].get(key) or key


def normalize_lang(lang: str) -> str:
    """把任意输入归一化为 zh_CN / en_US。"""
    return lang if lang in TRANSLATIONS else "zh_CN"
